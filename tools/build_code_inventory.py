"""
Generate research/context/CODE_INVENTORY.md: a deterministic, AST-based list of
the project's Python modules with their classes and top-level functions, line
numbers, first docstring line, size and the last commit that touched each file.

It reads only source text and git metadata (no imports, no execution), so it is
safe to run on any checkout. The meaning of each module (purpose, version,
experiments, papers) is curated by hand in research/context/CODE_ARCHITECTURE.md;
this file is the machine-generated index that keeps symbols and line numbers
current.

  python3 tools/build_code_inventory.py          # rewrite the inventory
  python3 tools/build_code_inventory.py --check  # exit 1 if it is out of date
"""
from __future__ import annotations

import ast
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research" / "context" / "CODE_INVENTORY.md"

# (group title, glob patterns relative to the repository root)
SCOPE = [
    ("Root modules: controllers, layers, pipelines", ["*.py"]),
    ("Detector and tracker adapters", ["adapters/**/*.py"]),
    ("V7 / V7f tools (development, external hosts, CI)", ["tools/v7/**/*.py"]),
    ("V6-TF tools", ["tools/v6/**/*.py"]),
    ("SCI + V7f and General AC-MOT G1 tools", ["tools/sci_v7/**/*.py"]),
    ("G2 compute-adaptation tools", ["tools/g2/**/*.py"]),
    ("OATrack tools", ["tools/oatrack/**/*.py"]),
    ("Shared tools (evaluation, caching, validation, context)", ["tools/*.py"]),
    ("Paper 1 experiment scripts (AC-MOT operating-point controller)",
     ["research/acmot_paper_v2/*.py", "research/acmot_paper_v2/controller_search/*.py",
      "research/acmot_paper_v2/step4/*.py"]),
    ("Manuscript build tools", ["JAIS_PAPERS/CODEX_HANDOFF/tools/*.py", "JAIS_PAPERS/refs/*.py"]),
    ("Tests", ["tests/*.py"]),
]

# Root files that .graphifyignore excludes because they belong to the archived
# original AC-MOT v12-v17 pipeline (history, see ARCHITECTURE.md section A).
ARCHIVED = {"experiment.py", "evaluate.py", "report.py", "core_v17.py", "portable_v15.py",
            "portable_v16.py", "portable_v17.py", "test_portability.py", "test_suite.py"}


def last_commit(rel: str) -> str:
    out = subprocess.run(["git", "log", "-1", "--format=%h %ad", "--date=short", "--", rel],
                         cwd=ROOT, capture_output=True, text=True).stdout.strip()
    return out or "untracked"


def first_line(doc: str | None) -> str:
    if not doc:
        return ""
    line = doc.strip().splitlines()[0].strip()
    return line.replace("|", "/")[:110]


def describe(path: Path) -> tuple[str, list[str]]:
    src = path.read_text(encoding="utf-8", errors="ignore")
    try:
        tree = ast.parse(src)
    except SyntaxError as exc:
        return f"(not parseable: {exc.msg})", []
    rows = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            methods = [f"{n.name} L{n.lineno}" for n in node.body
                       if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
                       and (not n.name.startswith("_") or n.name in ("__init__", "__call__"))]
            m = ", ".join(methods[:12]) + (" ..." if len(methods) > 12 else "")
            rows.append(f"class `{node.name}` L{node.lineno}" + (f" ({m})" if m else "")
                        + (f": {first_line(ast.get_docstring(node))}" if ast.get_docstring(node) else ""))
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            rows.append(f"def `{node.name}` L{node.lineno}"
                        + (f": {first_line(ast.get_docstring(node))}" if ast.get_docstring(node) else ""))
    return first_line(ast.get_docstring(tree)), rows


def files_for(patterns: list[str], seen: set[Path]) -> list[Path]:
    found = []
    for pat in patterns:
        for p in sorted(ROOT.glob(pat)):
            if p.is_file() and "__pycache__" not in p.parts and p not in seen:
                seen.add(p)
                found.append(p)
    return found


def build() -> str:
    lines = [
        "# CODE INVENTORY (generated — do not edit by hand)",
        "",
        "Generated by `tools/build_code_inventory.py` from the source AST and git",
        "metadata. Meaning, version and paper of each module: CODE_ARCHITECTURE.md.",
        "Regenerate after any code change; `--check` fails when this file is stale.",
        "",
    ]
    seen: set[Path] = set()
    total = 0
    for title, patterns in SCOPE:
        files = files_for(patterns, seen)
        if not files:
            continue
        lines += [f"## {title}", ""]
        for p in files:
            rel = str(p.relative_to(ROOT))
            doc, rows = describe(p)
            n = sum(1 for _ in p.open(encoding="utf-8", errors="ignore"))
            tag = " [ARCHIVED legacy pipeline]" if rel in ARCHIVED else ""
            lines.append(f"### `{rel}`{tag}")
            lines.append(f"- {n} lines; last commit {last_commit(rel)}"
                         + (f"; {doc}" if doc else ""))
            lines += [f"- {r}" for r in rows]
            lines.append("")
            total += 1
    lines.insert(5, f"Modules indexed: {total}.")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("CODE_INVENTORY.md is out of date: run tools/build_code_inventory.py")
            return 1
        print("CODE_INVENTORY.md up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
